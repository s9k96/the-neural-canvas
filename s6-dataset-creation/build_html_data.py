def _opus_sample(dec, n=10):
    """Even spread across the run, then guarantee one row of each status (taken late, where
    the threshold is live rather than in warmup). Ordered by step for readability."""
    if not dec:
        return []
    picked = {id(d): d for d in dec[::max(1, len(dec) // (n - 4))][:n - 4]}
    for status in ("accepted", "rejected", "deferred", "protected"):
        for d in reversed(dec):
            if d["status"] == status and d.get("threshold") is not None:
                picked.setdefault(id(d), d)
                break
    return sorted(picked.values(), key=lambda d: (d["global_step"], d["candidate_id"]))


def _tally(it):
    out = {}
    for x in it:
        out[x] = out.get(x, 0) + 1
    return dict(sorted(out.items(), key=lambda kv: -kv[1]))


def _events():
    """The [EVENT] and [PASS]/[FAIL] lines of run.log, in order."""
    out = []
    for line in (A / "run.log").read_text(encoding="utf-8").splitlines():
        for kind in ("EVENT", "PASS", "FAIL"):
            tag = f"[{kind}]"
            if tag in line:
                body = line.split(tag, 1)[1].strip()
                name, _, detail = body.partition(" -- ")
                out.append({"kind": kind, "name": name.strip(), "detail": detail.strip(),
                            "at": line.split("]")[0].strip("[ ").strip()})
                break
    return out


