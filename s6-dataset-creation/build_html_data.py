def _remap_and_store():
    store = shards.ShardStore(HERE / "shards")
    admitted = []

    class S:
        pass
    for p in (A / "manifests/shards").glob("*.json"):
        m = json.loads(p.read_text(encoding="utf-8"))
        if m["admission"]["verdict"] != "ADMITTED" or m.get("never_train"):
            continue
        o = S()
        o.shard_id, o.lane, o.manifest = m["shard_id"], m["capability_lane"], m
        o.tokens = np.load(HERE / "shards" / f"{m['shard_id']}.npz")["tokens"]
        admitted.append(o)
    remap, _ = shards.build_vocab_remap(admitted, 2048)
    return store, remap


def batch_anatomy(tok, limit=112):
    """Rebuild two real packed sequences from their recorded placements and expose the arrays
    the page draws -- through the production code path, so the page shows exactly what the
    system produced.

      'segments' picks the sequence with the most independently-packed samples (the
                 block-diagonal case);
      'masked'   picks the one with the largest context share, where the loss mask is doing
                 visible work (prompt and tool observations carried but not learned from).
    """
    rep = load("manifests/packed_batch_report.json")
    store, remap = _remap_and_store()
    picks = {}
    for b in rep["batches"]:
        if b.get("mode") != "train":
            continue
        for s in b["sequences"]:
            nseg = len({p["segment_id"] for p in s["placements"]})
            ctx = b["context_positions"] / max(1, b["positions"])
            if nseg >= 2 and nseg > picks.get("segments", (None, -1))[1]:
                picks["segments"] = ((s, b), nseg)
            if ctx > picks.get("masked", (None, -1))[1] and b["loss_bearing_positions"] > 0:
                picks["masked"] = ((s, b), ctx)
    out = {}
    for key, ((seq, batch), _) in picks.items():
        plan = packing.SeqPlan(seq["lane"], seq["policy"], rep["sequence_length"])
        plan.placements = seq["placements"]
        plan.used = seq["used_positions"]
        m = packing.materialize([plan], store, remap, rep["sequence_length"], firewall=None)
        # export far enough to include the first segment boundary -- the attention drawing is
        # pointless inside a single segment, where the mask is just a triangle
        seg = m.segment_ids[0]
        bnd = next((i for i in range(1, seg.size) if seg[i] != seg[i - 1] and seg[i] >= 0), None)
        want = max(limit, (bnd + 44) if bnd is not None else limit)
        n = min(want, int((seg >= 0).sum()) + 6, rep["sequence_length"])
        out[key] = {
            "lane": seq["lane"], "policy": seq["policy"],
            "sequence_length": rep["sequence_length"],
            "used": seq["used_positions"], "pad": seq["pad_positions"],
            "utilization": seq["utilization"],
            "segments": [{"segment_id": p["segment_id"], "shard_id": p["shard_id"],
                          "doc_id": p["doc_id"], "span_id": p["span_id"],
                          "dst": [p["dst_a"], p["dst_b"]]} for p in seq["placements"]],
            "shown": n,
            "tokens": [tok.decode([int(t)]) for t in m.tokens[0][:n]],
            "token_ids": [int(t) for t in m.tokens[0][:n]],
            "loss_mask": [int(x) for x in m.loss_mask[0][:n]],
            "is_target": [int(x) for x in m.is_target[0][:n]],
            "segment_ids": [int(x) for x in m.segment_ids[0][:n]],
            "position_ids": [int(x) for x in m.position_ids[0][:n]],
            "batch_hash": batch["batch_hash"],
            "loss_mask_hash": batch["loss_mask_hash"],
            "attention_mask_hash": batch["attention_mask_hash"],
            "stats": {k: batch[k] for k in ("positions", "used_positions", "pad_positions",
                                            "loss_bearing_positions", "context_positions",
                                            "utilization", "segments", "eos_inside")},
        }
    return out


